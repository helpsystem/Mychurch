/**
 * Returns today's active verse based on Day of Year (365 dynamic rotation)
 * or returns custom override if set in widget config.
 */
export function getTodayVerse(config?: {
    useCustomVerse?: boolean;
    verseFa?: string;
    verseEn?: string;
    refFa?: string;
    refEn?: string;
}): DailyVerseItem {
    if (config?.useCustomVerse && config?.verseFa?.trim()) {
        return {
            id: 0,
            verseFa: config.verseFa.trim(),
            verseEn: config.verseEn?.trim() || config.verseFa.trim(),
            refFa: config.refFa?.trim() || "کلام خدا",
            refEn: config.refEn?.trim() || "God's Word",
            themeFa: "آیه سفارشی روز",
            themeEn: "Custom Daily Verse"
        };
    }

    const now = new Date();
    const start = new Date(now.getFullYear(), 0, 0);
    const diff = (now.getTime() - start.getTime()) + ((start.getTimezoneOffset() - now.getTimezoneOffset()) * 60 * 1000);
    const oneDay = 1000 * 60 * 60 * 24;
    const dayOfYear = Math.max(1, Math.floor(diff / oneDay));

    const index = (dayOfYear - 1) % DAILY_VERSES.length;
    return DAILY_VERSES[index];
}
